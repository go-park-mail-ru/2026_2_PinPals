CREATE TABLE IF NOT EXISTS feedback (
    feedback_id  integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    integer     NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    is_complaint boolean     NOT NULL DEFAULT false,
    body         text        NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT feedback_body_not_blank CHECK (length(btrim(body)) > 0),
    CONSTRAINT feedback_body_max_len   CHECK (length(body) <= 5000)
);

CREATE INDEX IF NOT EXISTS feedback_author_idx  ON feedback (author_id);
CREATE INDEX IF NOT EXISTS feedback_created_idx ON feedback (created_at);

COMMENT ON TABLE  feedback              IS 'Отзывы и жалобы пользователей на сайт';
COMMENT ON COLUMN feedback.author_id    IS 'Кто оставил отзыв';
COMMENT ON COLUMN feedback.is_complaint IS 'true — жалоба, false — обычный отзыв';
COMMENT ON COLUMN feedback.body         IS 'Содержание отзыва';

