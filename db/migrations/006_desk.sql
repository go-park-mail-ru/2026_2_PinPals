CREATE TABLE desk (
    desk_id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id      integer     NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    name            text        NOT NULL DEFAULT 'Untitled desk',
    description     text,
    avatar_img_url  text,
    entry_status    smallint    NOT NULL DEFAULT 0 CHECK (entry_status IN (0, 1, 2)),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    deleted_at      timestamptz DEFAULT NULL
);

